package my.unifi.eset.keycloak.piidataencryption.crypto;

import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import javax.crypto.Cipher;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.IvParameterSpec;
import javax.crypto.spec.SecretKeySpec;
import org.apache.commons.codec.digest.DigestUtils;
import org.apache.commons.lang3.ArrayUtils;
import org.jboss.logging.Logger;
import org.keycloak.quarkus.runtime.configuration.Configuration;

/**
 * Envelope encryption for PII with versioned keys, AAD and a blind index.
 *
 * <p>
 * Every value is encrypted with its own random data key (DEK). The DEK is
 * wrapped (encrypted) by the active master key (KEK), and both the wrapped DEK
 * and the ciphertext are stored together, each prefixed by the version of the
 * key that produced them:</p>
 *
 * <pre>
 *   $$$v1:&lt;KEK version&gt;:&lt;wrapped DEK&gt;:&lt;ciphertext&gt;
 *          └ envelope     └ DEK encrypted   └ value encrypted
 *            layout         by the KEK        by the DEK
 * </pre>
 *
 * <p>
 * Because the version is part of the stored value, a master key can be rotated
 * by adding the new key to {@code KC_PII_ENCKEY} and marking it active: new
 * values are wrapped with it, while old values keep decrypting with the old
 * key. {@link #rewrapDataKey(ProtectedValue)} re-wraps the DEK of an existing
 * value so the old master key can eventually be dropped without re-encrypting
 * the PII itself.</p>
 *
 * <p>
 * Values are encrypted with AES-256-GCM, so the ciphertext is authenticated.
 * The AAD (additional authenticated data) binds a value to its owner and field
 * ({@link #fieldContext(String, String, String)}), which prevents moving a
 * ciphertext to another row or column.</p>
 *
 * <p>
 * For filtering, {@link #search(String, PiiKind)} produces an HMAC-SHA256 blind
 * index keyed with a secret, versioned pepper.</p>
 *
 * @author Makara Mas <support@makaramas.com>
 */
public final class PiiCipher {

    /**
     * Environment variable that holds the master keys (KEK) in the format
     * {@code v1:<base64 key>,v2:<base64 key>}.
     */
    public static final String ENV_MASTER_KEYS = "KC_PII_ENCKEY";

    /**
     * Environment variable that holds the version of the master key used to
     * wrap new data keys. Defaults to the last key of {@link #ENV_MASTER_KEYS}.
     */
    public static final String ENV_MASTER_ACTIVE_KEY = "KC_PII_ENCKEY_ACTIVE";

    /**
     * Environment variable that holds the peppers for the blind index in the
     * same format as {@link #ENV_MASTER_KEYS}. When it is not set, a pepper is
     * derived from the first (oldest) master key so that existing deployment
     * only needs to configure a single variable.
     */
    public static final String ENV_INDEX_KEYS = "KC_PII_INDEXKEY";

    /**
     * Environment variable that holds the version of the pepper used for new
     * blind indexes.
     */
    public static final String ENV_INDEX_ACTIVE_KEY = "KC_PII_INDEXKEY_ACTIVE";

    /**
     * AES-GCM authenticates both the DEK wrapping and the value itself.
     */
    static final String ALGORITHM = "AES/GCM/NoPadding";

    /**
     * Algorithm used by ciphertext generated by version 1.x of this provider.
     * Only used to read (and later migrate) old values.
     */
    static final String LEGACY_ALGORITHM = "AES/CBC/PKCS5Padding";

    static final int GCM_IV_LENGTH = 12;
    static final int GCM_TAG_BITS = 128;
    static final int DATA_KEY_LENGTH = 32;
    static final int LEGACY_IV_LENGTH = 16;

    private static final String DEK_CONTEXT = "pii-dek";
    private static final String PEPPER_DERIVATION_LABEL = "pii-blind-index-v1";

    private static final SecureRandom RANDOM = new SecureRandom();
    private static final Logger logger = Logger.getLogger(PiiCipher.class);

    private static volatile PiiCipher instance;

    private final KeyRing masterKeys;
    private final BlindIndex blindIndex;

    private PiiCipher(KeyRing masterKeys, BlindIndex blindIndex) {
        this.masterKeys = masterKeys;
        this.blindIndex = blindIndex;
    }

    /**
     * @return The process wide cipher configured from the environment
     * @throws IllegalArgumentException when the configuration is missing or
     * invalid
     */
    public static PiiCipher getInstance() {
        PiiCipher current = instance;
        if (current == null) {
            synchronized (PiiCipher.class) {
                current = instance;
                if (current == null) {
                    current = fromEnv();
                    instance = current;
                }
            }
        }
        return current;
    }

    /**
     * Builds a cipher from the environment without caching it.
     *
     * @return The configured cipher
     * @throws IllegalArgumentException when the configuration is missing or
     * invalid
     */
    public static PiiCipher fromEnv() {
        KeyRing master = KeyRing.parse(resolveMasterKeyMaterial(), System.getenv(ENV_MASTER_ACTIVE_KEY), ENV_MASTER_KEYS);
        return new PiiCipher(master, new BlindIndex(resolveIndexKeys(master)));
    }

    /**
     * Drops the cached instance so the next {@link #getInstance()} call re-reads
     * the environment. Intended for tests and for configuration changes.
     */
    static synchronized void reset() {
        instance = null;
    }

    /**
     * Builds the AAD that binds a protected value to its owner and field, e.g.
     * {@code user:<user id>:email}. The AAD is not secret, it only has to be
     * rebuilt identically when decrypting.
     *
     * @param scope The kind of entity, e.g. {@code user}
     * @param id Identifier of the entity instance
     * @param field The field name
     * @return The AAD
     */
    public static String fieldContext(String scope, String id, String field) {
        return scope + ":" + id + ":" + field;
    }

    /**
     * @param value The value to check
     * @return true if the value is an encrypted value in any supported format
     */
    public static boolean isProtected(String value) {
        return ProtectedValue.isProtected(value);
    }

    /**
     * @return The version of the master key used to wrap new data keys
     */
    public String getActiveKeyVersion() {
        return masterKeys.getActiveVersion();
    }

    /**
     * Encrypts a value with a fresh data key.
     *
     * @param plaintext The value to encrypt
     * @param aad The AAD that binds the value to its owner and field, may be
     * null for values that are not tied to a row
     * @return The protected value
     */
    public ProtectedValue encrypt(String plaintext, String aad) {
        if (plaintext == null) {
            return null;
        }
        byte[] dataKey = new byte[DATA_KEY_LENGTH];
        RANDOM.nextBytes(dataKey);
        String keyVersion = masterKeys.getActiveVersion();
        try {
            return new ProtectedValue(
                    wrapDataKey(dataKey, keyVersion),
                    seal(dataKey, plaintext.getBytes(StandardCharsets.UTF_8), aad),
                    null);
        } catch (GeneralSecurityException ex) {
            throw new IllegalStateException("Unable to encrypt PII value", ex);
        }
    }

    /**
     * Encrypts a value and computes its blind index.
     *
     * @param plaintext The value to encrypt
     * @param kind The kind of value, used for canonicalization before hashing
     * @param aad The AAD that binds the value to its owner and field
     * @return The protected value, with the blind index attached
     */
    public ProtectedValue protect(String plaintext, PiiKind kind, String aad) {
        ProtectedValue value = encrypt(plaintext, aad);
        return value == null ? null : value.withIndex(search(plaintext, kind));
    }

    /**
     * Decrypts a protected value.
     *
     * @param value The protected value
     * @param aad The AAD used when the value was encrypted
     * @return The plaintext
     * @throws IllegalStateException when the value cannot be decrypted, e.g.
     * because the key version is no longer configured or the AAD differs
     */
    public String decrypt(ProtectedValue value, String aad) {
        if (value == null) {
            return null;
        }
        try {
            byte[] dataKey = unwrapDataKey(value.getDataKey());
            return open(dataKey, value.getCiphertext(), aad);
        } catch (GeneralSecurityException | IllegalArgumentException ex) {
            throw new IllegalStateException("Unable to decrypt PII value (key version " + value.getKeyVersion() + "): " + ex.getMessage(), ex);
        }
    }

    /**
     * Encrypts a value and returns it in the serialized single column format.
     *
     * @param plaintext The value to encrypt
     * @param aad The AAD that binds the value to its owner and field
     * @return The serialized protected value
     */
    public String encryptString(String plaintext, String aad) {
        if (plaintext == null) {
            return null;
        }
        return encrypt(plaintext, aad).serialize();
    }

    /**
     * Decrypts a value stored in the serialized format. Plaintext values,
     * unknown values and values from version 1.x are passed through when they
     * cannot be decrypted. Values from version 1.x are decrypted with the
     * legacy algorithm.
     *
     * @param protectedValue The stored value
     * @param aad The AAD used when the value was encrypted
     * @return The plaintext, or the passed value when it is not decryptable
     */
    public String decryptString(String protectedValue, String aad) {
        if (protectedValue == null || !isProtected(protectedValue)) {
            return protectedValue;
        }
        ProtectedValue value = ProtectedValue.parse(protectedValue);
        if (value == null) {
            String legacy = decryptLegacy(protectedValue);
            return legacy != null ? legacy : protectedValue;
        }
        try {
            return decrypt(value, aad);
        } catch (IllegalStateException | IllegalArgumentException ex) {
            logger.debugf("Event: PII_DECRYPTION_FAILURE, Reason: %s", ex.getMessage());
            return protectedValue;
        }
    }

    /**
     * Re-wraps the data key of a protected value with the active master key.
     * The ciphertext is left untouched, so this is the cheap half of a key
     * rotation.
     *
     * @param value The protected value
     * @return The protected value with its data key re-wrapped, or the passed
     * value when it is already wrapped with the active master key
     * @throws IllegalStateException when the data key cannot be unwrapped, e.g.
     * because its key version is no longer configured
     */
    public ProtectedValue rewrapDataKey(ProtectedValue value) {
        if (value == null) {
            return null;
        }
        String activeVersion = masterKeys.getActiveVersion();
        if (value.getKeyVersion().equals(activeVersion)) {
            return value;
        }
        try {
            byte[] dataKey = unwrapDataKey(value.getDataKey());
            return value.withDataKey(wrapDataKey(dataKey, activeVersion));
        } catch (GeneralSecurityException | IllegalArgumentException ex) {
            throw new IllegalStateException("Unable to re-wrap PII data key (key version " + value.getKeyVersion() + "): " + ex.getMessage(), ex);
        }
    }

    /**
     * Replaces the data key of a protected value and re-encrypts the value with
     * it. The blind index is kept as is, because it does not depend on the data
     * key.
     *
     * @param value The protected value
     * @param aad The AAD used when the value was encrypted
     * @return The protected value re-encrypted with a fresh data key
     */
    public ProtectedValue rotateDataKey(ProtectedValue value, String aad) {
        if (value == null) {
            return null;
        }
        String plaintext = decrypt(value, aad);
        return encrypt(plaintext, aad).withIndex(value.getIndex());
    }

    /**
     * @param value The protected value
     * @return true if the data key is not wrapped with the active master key
     */
    public boolean needsRotation(ProtectedValue value) {
        return value != null && !value.getKeyVersion().equals(masterKeys.getActiveVersion());
    }

    /**
     * @param protectedValue The stored value
     * @return true if the value is in the current envelope format and its data
     * key is not wrapped with the active master key
     */
    public boolean needsRotation(String protectedValue) {
        return needsRotation(ProtectedValue.parse(protectedValue));
    }

    /**
     * Computes the blind index of a value with the active pepper.
     *
     * @param value The plaintext value
     * @param kind The kind of value, used for canonicalization
     * @return The blind index, or null if the value is null
     */
    public String search(String value, PiiKind kind) {
        return blindIndex.search(value, kind);
    }

    /**
     * Computes the blind indexes of a value with every configured pepper, plus
     * the legacy SHA-1 hash.
     *
     * @param value The plaintext value
     * @param kind The kind of value, used for canonicalization
     * @return The candidate hashes, the active one first
     */
    public List<String> searchAll(String value, PiiKind kind) {
        return blindIndex.searchAll(value, kind);
    }

    /**
     * @param storedHash The hash read from the database
     * @param value The plaintext value
     * @param kind The kind of value, used for canonicalization
     * @return true if the stored hash belongs to the passed value
     */
    public boolean matchesHash(String storedHash, String value, PiiKind kind) {
        return blindIndex.matches(storedHash, value, kind);
    }

    private String wrapDataKey(byte[] dataKey, String keyVersion) {
        byte[] kek = masterKeys.get(keyVersion);
        if (kek == null) {
            throw new IllegalArgumentException("Key version " + keyVersion + " is not configured in " + ENV_MASTER_KEYS + ".");
        }
        try {
            return keyVersion + ":" + Base64.getEncoder().encodeToString(sealBytes(kek, dataKey, DEK_CONTEXT + ":" + keyVersion));
        } catch (GeneralSecurityException ex) {
            throw new IllegalStateException("Unable to wrap PII data key", ex);
        }
    }

    private byte[] unwrapDataKey(String dataKey) throws GeneralSecurityException {
        int separator = dataKey.indexOf(':');
        if (separator < 0) {
            throw new IllegalArgumentException("Data key has no key version prefix");
        }
        String keyVersion = dataKey.substring(0, separator);
        byte[] kek = masterKeys.get(keyVersion);
        if (kek == null) {
            throw new IllegalArgumentException("Key version " + keyVersion + " is not configured in " + ENV_MASTER_KEYS + ".");
        }
        byte[] wrapped = Base64.getDecoder().decode(dataKey.substring(separator + 1));
        return openBytes(kek, wrapped, DEK_CONTEXT + ":" + keyVersion);
    }

    private String decryptLegacy(String protectedValue) {
        byte[] payload;
        try {
            payload = Base64.getDecoder().decode(protectedValue.substring(ProtectedValue.CIPHERTEXT_PREFIX.length()));
        } catch (IllegalArgumentException ex) {
            return null;
        }
        if (payload.length <= LEGACY_IV_LENGTH) {
            return null;
        }
        byte[] iv = ArrayUtils.subarray(payload, 0, LEGACY_IV_LENGTH);
        byte[] ciphertext = ArrayUtils.subarray(payload, LEGACY_IV_LENGTH, payload.length);
        for (KeyRing.Entry entry : masterKeys.getEntries()) {
            try {
                Cipher cipher = Cipher.getInstance(LEGACY_ALGORITHM);
                cipher.init(Cipher.DECRYPT_MODE, new SecretKeySpec(entry.key(), "AES"), new IvParameterSpec(iv));
                return new String(cipher.doFinal(ciphertext), StandardCharsets.UTF_8);
            } catch (GeneralSecurityException | IllegalArgumentException ex) {
                // wrong key, try the next one
            }
        }
        logger.debugf("Event: PII_LEGACY_DECRYPTION_FAILURE, Reason: no configured key is able to decrypt the value");
        return null;
    }

    private static String seal(byte[] key, byte[] plaintext, String aad) throws GeneralSecurityException {
        return Base64.getEncoder().encodeToString(sealBytes(key, plaintext, aad));
    }

    private static String open(byte[] key, String ciphertext, String aad) throws GeneralSecurityException {
        return new String(openBytes(key, Base64.getDecoder().decode(ciphertext), aad), StandardCharsets.UTF_8);
    }

    private static byte[] sealBytes(byte[] key, byte[] plaintext, String aad) throws GeneralSecurityException {
        byte[] iv = new byte[GCM_IV_LENGTH];
        RANDOM.nextBytes(iv);
        Cipher cipher = Cipher.getInstance(ALGORITHM);
        cipher.init(Cipher.ENCRYPT_MODE, new SecretKeySpec(key, "AES"), new GCMParameterSpec(GCM_TAG_BITS, iv));
        if (aad != null && !aad.isEmpty()) {
            cipher.updateAAD(aad.getBytes(StandardCharsets.UTF_8));
        }
        return ArrayUtils.addAll(iv, cipher.doFinal(plaintext));
    }

    private static byte[] openBytes(byte[] key, byte[] payload, String aad) throws GeneralSecurityException {
        if (payload.length <= GCM_IV_LENGTH) {
            throw new GeneralSecurityException("Ciphertext is too short");
        }
        byte[] iv = ArrayUtils.subarray(payload, 0, GCM_IV_LENGTH);
        byte[] encrypted = ArrayUtils.subarray(payload, GCM_IV_LENGTH, payload.length);
        Cipher cipher = Cipher.getInstance(ALGORITHM);
        cipher.init(Cipher.DECRYPT_MODE, new SecretKeySpec(key, "AES"), new GCMParameterSpec(GCM_TAG_BITS, iv));
        if (aad != null && !aad.isEmpty()) {
            cipher.updateAAD(aad.getBytes(StandardCharsets.UTF_8));
        }
        return cipher.doFinal(encrypted);
    }

    private static KeyRing resolveIndexKeys(KeyRing masterKeys) {
        String configured = System.getenv(ENV_INDEX_KEYS);
        if (configured != null && !configured.isBlank()) {
            return KeyRing.parse(configured, System.getenv(ENV_INDEX_ACTIVE_KEY), ENV_INDEX_KEYS);
        }
        String version = masterKeys.getVersions().get(0);
        byte[] derived = derivePepper(masterKeys.get(version));
        Map<String, byte[]> keys = new LinkedHashMap<>();
        keys.put(version, derived);
        logger.debugf("Event: PII_INDEX_PEPPER_DERIVED, Source: %s, Version: %s", ENV_MASTER_KEYS, version);
        return KeyRing.of(keys, version, ENV_INDEX_KEYS);
    }

    private static byte[] derivePepper(byte[] masterKey) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            digest.update(masterKey);
            return digest.digest(PEPPER_DERIVATION_LABEL.getBytes(StandardCharsets.UTF_8));
        } catch (NoSuchAlgorithmException ex) {
            throw new IllegalStateException("Unable to derive the blind index pepper", ex);
        }
    }

    private static String resolveMasterKeyMaterial() {
        String configured = System.getenv(ENV_MASTER_KEYS);
        if (configured != null && !configured.isBlank()) {
            return configured;
        }
        String dbUrl = null;
        try {
            dbUrl = Configuration.getKcConfigValue("db-url").getRawValue();
        } catch (RuntimeException ex) {
            // no db-url configured, reported below
        }
        if (dbUrl == null || dbUrl.isBlank()) {
            throw new IllegalArgumentException("Encryption key is not configured. Set the " + ENV_MASTER_KEYS + " environment variable using the format v1:<base64 key>, e.g. v1:" + KeyRing.generateKey() + ".");
        }
        String derived = DigestUtils.md5Hex(dbUrl.getBytes(StandardCharsets.UTF_8)).toLowerCase();
        logger.warnf("Encryption key version %s was generated using MD5 hash of the JDBC URL of the database. It is recommended to set this key as %s environment variable.", KeyRing.LEGACY_VERSION, ENV_MASTER_KEYS);
        return derived;
    }

}
